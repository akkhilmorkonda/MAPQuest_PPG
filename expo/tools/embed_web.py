"""Embed expo/web into the firmware: the page as web_page.h, its files as web_assets.h.

The page is web/dashboard.html, marked for the board (dashserve.board_page):
the iPad's run and technical screens plus the operator panel. The ESP32
serves it and the files it loads (logo, fonts) from flash,
so the sketch needs them as C arrays. Edit expo/web, then run:

    python expo/tools/embed_web.py

``--check`` exits 1 if any header is out of date (the tests run it too).
The files embedded are the dashboard server's list (host/expotool/dashserve.py
ASSETS): the iPad page is built from the dashboard and loads the same ones.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

EXPO = Path(__file__).resolve().parent.parent
WEB = EXPO / "web"
SOURCE = WEB / "dashboard.html"
# Every sketch that serves the page gets its own copy (an Arduino sketch can
# only include files from its own folder).
SKETCHES = [EXPO / "firmware" / "expo_link_sim", EXPO / "firmware" / "expo_fw"]
DELIM = "EXPOHTML"

sys.path.insert(0, str(EXPO / "host"))
from expotool.dashserve import ASSETS, board_page  # noqa: E402


def render(html: str) -> str:
    if f"){DELIM}\"" in html:
        raise ValueError(f"the page contains the raw-string terminator ){DELIM}\"")
    return (
        "// GENERATED by expo/tools/embed_web.py from expo/web/dashboard.html. Do not edit:\n"
        "// change the page and run the script again.\n\n"
        "#pragma once\n\n"
        f"static const char WEB_INDEX_HTML[] = R\"{DELIM}({html}){DELIM}\";\n"
    )


def render_assets(assets: dict[str, str] = ASSETS, web: Path = WEB) -> str:
    """One byte array per file, and a table of (path, type, data, length)."""
    out = [
        "// GENERATED by expo/tools/embed_web.py from expo/web (the files the page loads).",
        "// Do not edit: change the files and run the script again.",
        "",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char    *path;     // as requested, e.g. /fonts/x.woff2",
        "  const char    *type;     // Content-Type",
        "  const uint8_t *data;",
        "  size_t         len;",
        "};",
        "",
    ]
    rows = []
    for i, (path, ctype) in enumerate(sorted(assets.items())):
        data = (web / path.lstrip("/")).read_bytes()
        out.append(f"// {path} ({len(data):,} bytes)")
        out.append(f"static const uint8_t WEB_ASSET_{i}[] = {{")
        for k in range(0, len(data), 20):
            out.append("  " + ",".join(f"0x{b:02x}" for b in data[k:k + 20]) + ",")
        out.append("};")
        rows.append(f'  {{"{path}", "{ctype}", WEB_ASSET_{i}, sizeof(WEB_ASSET_{i})}},')
    out.append("")
    out.append("static const WebAsset WEB_ASSETS[] = {")
    out += rows
    out.append("};")
    out.append(f"static const size_t WEB_ASSET_COUNT = {len(rows)};")
    return "\n".join(out) + "\n"


def outputs() -> dict[Path, str]:
    page = render(board_page(SOURCE.read_text(encoding="utf-8")))
    assets = render_assets()
    files = {}
    for sketch in SKETCHES:
        files[sketch / "web_page.h"] = page
        files[sketch / "web_assets.h"] = assets
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report whether the headers are current")
    args = ap.parse_args(argv)
    stale = []
    for target, text in outputs().items():
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        stale.append(target)
        if not args.check:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {target.relative_to(EXPO.parent)} ({len(text):,} bytes)")
    if args.check and stale:
        for t in stale:
            print(f"out of date: {t.relative_to(EXPO.parent)}  (run python expo/tools/embed_web.py)")
        return 1
    if not stale:
        print("web_page.h and web_assets.h up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
