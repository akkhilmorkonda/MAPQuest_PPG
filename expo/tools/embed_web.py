"""Embed expo/web/index.html into the firmware as web_page.h.

The ESP32 serves the page from flash, so the sketch needs it as a C string.
Edit expo/web/index.html, then run:

    python expo/tools/embed_web.py

``--check`` exits 1 if any header is out of date (the tests run it too).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

EXPO = Path(__file__).resolve().parent.parent
SOURCE = EXPO / "web" / "index.html"
# Every sketch that serves the page gets its own copy (an Arduino sketch can
# only include files from its own folder).
TARGETS = [
    EXPO / "firmware" / "expo_link_sim" / "web_page.h",
    EXPO / "firmware" / "expo_fw" / "web_page.h",
]
DELIM = "EXPOHTML"


def render(html: str) -> str:
    if f"){DELIM}\"" in html:
        raise ValueError(f"the page contains the raw-string terminator ){DELIM}\"")
    return (
        "// GENERATED by expo/tools/embed_web.py from expo/web/index.html. Do not edit:\n"
        "// change the page and run the script again.\n\n"
        "#pragma once\n\n"
        f"static const char WEB_INDEX_HTML[] = R\"{DELIM}({html}){DELIM}\";\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report whether the headers are current")
    args = ap.parse_args(argv)
    text = render(SOURCE.read_text(encoding="utf-8"))
    stale = []
    for target in TARGETS:
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        stale.append(target)
        if not args.check:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {target.relative_to(EXPO.parent)} ({len(text):,} bytes)")
    if args.check and stale:
        for t in stale:
            print(f"out of date: {t.relative_to(EXPO.parent)}  (run python expo/tools/embed_web.py)")
        return 1
    if not stale:
        print("web_page.h up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
